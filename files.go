package umbra

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"iter"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

const (
	extension = ".pii"
	header    = "# Code generated by umbra. DO NOT EDIT.\n"
)

// Load reads a catalog from the files [Catalog.WriteDir] wrote, and checks each table
// against the policy. It reports every problem at once.
func Load(fsys fs.FS, policy Policy) (*Catalog, error) {
	if err := policy.check(); err != nil {
		return nil, err
	}

	files, err := readFiles(fsys)
	if err != nil {
		return nil, err
	}

	catalog := &Catalog{}

	var problems []error

	for _, name := range slices.Sorted(maps.Keys(files)) {
		directory, file := path.Split(name)
		table, isCatalogFile := strings.CutSuffix(file, extension)

		if !isCatalogFile || directory == "" {
			problems = append(problems, fmt.Errorf("%s: not a catalog file, which is dataset/table%s", name, extension))

			continue
		}

		columns, fileProblems := parseFile(name, files[name], policy)
		if len(fileProblems) == 0 {
			fileProblems = catalog.add(policy, strings.TrimSuffix(directory, "/"), Table{Name: table, Columns: columns})
		}

		problems = append(problems, fileProblems...)
	}

	if len(problems) > 0 {
		return nil, errors.Join(problems...)
	}

	return catalog, nil
}

// WriteDir writes the catalog to dir, one file per table at dataset/table.pii, each line
// a column and its tag. It rewrites only the files that changed, and removes the .pii
// files of tables the catalog no longer has.
func (c *Catalog) WriteDir(dir string) error {
	files := c.files()

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	written, err := readFiles(os.DirFS(dir))
	if err != nil {
		return err
	}

	for name := range written {
		if _, isCatalogued := files[name]; !isCatalogued && path.Ext(name) == extension {
			if err := os.Remove(filepath.Join(dir, filepath.FromSlash(name))); err != nil {
				return err
			}
		}
	}

	for _, name := range slices.Sorted(maps.Keys(files)) {
		if bytes.Equal(written[name], files[name]) {
			continue
		}

		target := filepath.Join(dir, filepath.FromSlash(name))

		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}

		if err := os.WriteFile(target, files[name], 0o644); err != nil {
			return err
		}
	}

	return nil
}

// Verify reports each file in fsys that differs from what [Catalog.WriteDir] would write:
// one that is missing, one whose content differs, and one the catalog has no table for.
func (c *Catalog) Verify(fsys fs.FS) error {
	written, err := readFiles(fsys)
	if err != nil {
		return err
	}

	files := c.files()

	var problems []error

	for _, name := range union(maps.Keys(written), maps.Keys(files)) {
		content, isWritten := written[name]
		want, isCatalogued := files[name]

		switch {
		case !isWritten:
			problems = append(problems, fmt.Errorf("%s is missing", name))
		case !isCatalogued:
			problems = append(problems, fmt.Errorf("%s is not in the catalog", name))
		case !bytes.Equal(content, want):
			problems = append(problems, fmt.Errorf("%s differs", name))
		}
	}

	return errors.Join(problems...)
}

// files renders each table's file, by its path.
func (c *Catalog) files() map[string][]byte {
	files := map[string][]byte{}

	for dataset, tables := range c.datasets {
		for name, table := range tables {
			var content bytes.Buffer

			content.WriteString(header)

			for _, column := range table.Columns {
				fmt.Fprintf(&content, "%s %s\n", column.Name, column.Class)
			}

			files[path.Join(dataset, name+extension)] = content.Bytes()
		}
	}

	return files
}

// parseFile reads a table's columns from its file: one column and its tag to a line.
// It skips blank lines and lines that start with #.
func parseFile(name string, content []byte, policy Policy) ([]Column, []error) {
	var (
		columns  []Column
		problems []error
	)

	number := 0

	for line := range strings.Lines(string(content)) {
		number++

		words := strings.Fields(line)
		if len(words) == 0 || strings.HasPrefix(words[0], "#") {
			continue
		}

		if len(words) != 2 {
			problems = append(problems, fmt.Errorf("%s:%d: want a column and its tag", name, number))

			continue
		}

		class, err := ParseTag(words[1], policy)
		if err != nil {
			problems = append(problems, fmt.Errorf("%s:%d: %w", name, number, err))

			continue
		}

		columns = append(columns, Column{Name: words[0], Class: class})
	}

	return columns, problems
}

// readFiles reads every file under fsys by its path, except those hidden by a leading dot.
func readFiles(fsys fs.FS) (map[string][]byte, error) {
	files := map[string][]byte{}

	err := fs.WalkDir(fsys, ".", func(name string, entry fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case name != "." && strings.HasPrefix(entry.Name(), "."):
			if entry.IsDir() {
				return fs.SkipDir
			}

			return nil
		case entry.IsDir():
			return nil
		}

		content, err := fs.ReadFile(fsys, name)
		files[name] = content

		return err
	})

	return files, err
}

// union returns the names in either sequence, sorted, each once.
func union(first, second iter.Seq[string]) []string {
	names := slices.AppendSeq(slices.Collect(first), second)
	slices.Sort(names)

	return slices.Compact(names)
}
