const generated = "# Code generated by umbra. DO NOT EDIT.\n"

func TestLoadRefusesABrokenFile(t *testing.T) {
	tests := map[string]struct {
		files fstest.MapFS
		want  string
	}{
		"a line with no tag": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte("id\n")}},
			"postgres/t.pii:1: want a column and its tag",
		},
		"a line with two tags": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte(generated + "id allow\nname deny=person allow\n")}},
			"postgres/t.pii:3: want a column and its tag",
		},
		"a tag the policy doesn't know": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte(generated + "\nid allow\nemail generalise=email\n")}},
			`postgres/t.pii:4: unknown term "generalise=email"; use ` + terms,
		},
		"a column twice": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte("id allow\nid deny=internal\n")}},
			"postgres t.id: classified twice",
		},
		"no columns": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte(generated)}},
			"postgres t: no columns",
		},
		"a file outside a dataset": {
			fstest.MapFS{"t.pii": {Data: []byte("id allow\n")}},
			"t.pii: not a catalog file, which is dataset/table.pii",
		},
		"a file of another kind": {
			fstest.MapFS{"postgres/t.yaml": {Data: []byte("id allow\n")}},
			"postgres/t.yaml: not a catalog file, which is dataset/table.pii",
		},
		"a rule of the policy": {
			fstest.MapFS{"postgres/t.pii": {Data: []byte("profile allow=business_data\n")}},
			"postgres t: profile: allow=business_data is only for accounts",
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			_, err := umbra.Load(test.files, policy())
			if err == nil || err.Error() != test.want {
				t.Errorf("got %v, want %s", err, test.want)
			}
		})
	}
}

func TestLoadReadsNestedDatasetsAndSkipsHiddenFiles(t *testing.T) {
	catalog, err := umbra.Load(fstest.MapFS{
		"bigquery/org/events.pii":    {Data: []byte("id allow\nproperties.email generalise=domain\n")},
		"bigquery/org/.DS_Store":     {Data: []byte{0, 1}},
		".git/postgres/old.pii.orig": {Data: []byte("not a catalog")},
	}, policy())
	if err != nil {
		t.Fatal(err)
	}

	events, isFound := catalog.Table("bigquery/org", "events")
	want := umbra.Table{Name: "events", Columns: []umbra.Column{
		{Name: "id", Class: umbra.Allow{}},
		{Name: "properties.email", Class: masks("generalise=domain")},
	}}

	if !isFound || !reflect.DeepEqual(events, want) {
		t.Errorf("got %v, want %v", events, want)
	}
}

func TestWriteDirRewritesOnlyWhatChanged(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "README.md", "Generated by go generate.\n")

	first := catalogOf(t, func(postgres *umbra.Dataset) {
		postgres.Columns("contacts", umbra.Tag("id", "allow"), umbra.Tag("name", "deny=person"))
		postgres.Columns("users", umbra.Tag("id", "allow"))
		postgres.Columns("accounts", umbra.Tag("id", "allow"))
	})

	if err := first.WriteDir(dir); err != nil {
		t.Fatal(err)
	}

	long := time.Date(2020, time.January, 1, 0, 0, 0, 0, time.UTC)
	if err := os.Chtimes(filepath.Join(dir, "postgres", "accounts.pii"), long, long); err != nil {
		t.Fatal(err)
	}

	second := catalogOf(t, func(postgres *umbra.Dataset) {
		postgres.Columns("contacts", umbra.Tag("id", "allow"), umbra.Tag("name", "deny=person"), umbra.Tag("email", "deny=person"))
		postgres.Columns("accounts", umbra.Tag("id", "allow"))
	})

	if err := second.WriteDir(dir); err != nil {
		t.Fatal(err)
	}

	if got := read(t, dir, "postgres/contacts.pii"); got != generated+"id allow\nname deny=person\nemail deny=person\n" {
		t.Errorf("contacts.pii is %q", got)
	}

	if _, err := os.Stat(filepath.Join(dir, "postgres", "users.pii")); !os.IsNotExist(err) {
		t.Errorf("users.pii is still there: %v", err)
	}

	if info, err := os.Stat(filepath.Join(dir, "postgres", "accounts.pii")); err != nil || !info.ModTime().Equal(long) {
		t.Errorf("accounts.pii was rewritten: %v", err)
	}

	if got := read(t, dir, "README.md"); got != "Generated by go generate.\n" {
		t.Errorf("README.md is %q", got)
	}

	if err := os.Remove(filepath.Join(dir, "README.md")); err != nil {
		t.Fatal(err)
	}

	files := os.DirFS(dir)

	if err := second.Verify(files); err != nil {
		t.Error(err)
	}

	loaded, err := umbra.Load(files, policy())
	if err != nil {
		t.Fatal(err)
	}

	if !reflect.DeepEqual(loaded, second) {
		t.Errorf("loads as %v, not %v", loaded, second)
	}
}

func catalogOf(t *testing.T, register func(postgres *umbra.Dataset)) *umbra.Catalog {
	t.Helper()

	registry := umbra.NewRegistry(policy(), nil)
	register(registry.Dataset("postgres"))

	catalog, err := registry.Catalog()
	if err != nil {
		t.Fatal(err)
	}

	return catalog
}

func write(t *testing.T, dir, name, content string) {
	t.Helper()

	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, dir, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
	if err != nil {
		t.Fatal(err)
	}

	return string(content)
}
