package umbra_test

import (
	"reflect"
	"slices"
	"testing"
	"testing/fstest"

	"github.com/feds01/umbra"
)

const (
	reasons = "credential, person, free_text, json or internal"
	terms   = "allow, deny=<reason>, generalise=domain, generalise=host or pseudonymise"
)

// masks returns the class that masks with the policy's maskers for terms, in that order.
func masks(terms ...string) umbra.Mask {
	var mask umbra.Mask

	for _, term := range terms {
		index := slices.IndexFunc(policy().Maskers, func(masker umbra.Masker) bool { return masker.Term == term })
		mask.Maskers = append(mask.Maskers, policy().Maskers[index])
	}

	return mask
}

func TestParseTag(t *testing.T) {
	tests := []struct {
		tag  string
		want umbra.Class
	}{
		{"allow", umbra.Allow{}},
		{"allow=business_data", umbra.Allow{Basis: "business_data"}},
		{"deny=person", umbra.Deny{Reason: "person"}},
		{"generalise=host", masks("generalise=host")},
		{"generalise=domain,pseudonymise", masks("generalise=domain", "pseudonymise")},
		{"pseudonymise,generalise=domain", masks("pseudonymise", "generalise=domain")},
	}

	for _, test := range tests {
		t.Run(test.tag, func(t *testing.T) {
			class, err := umbra.ParseTag(test.tag, policy())
			if err != nil {
				t.Fatal(err)
			}

			if !reflect.DeepEqual(class, test.want) {
				t.Errorf("got %#v, want %#v", class, test.want)
			}

			if class.String() != test.tag {
				t.Errorf("prints back as %q", class)
			}
		})
	}
}

func TestParseTagRefuses(t *testing.T) {
	tests := []struct {
		tag  string
		want string
	}{
		{"", "empty tag"},
		{"Allow", `unknown term "Allow"; use ` + terms},
		{" allow", `unknown term " allow"; use ` + terms},
		{"allow=because", `unknown basis "because"; use business_data`},
		{"allow=", `unknown basis ""; use business_data`},
		{"deny", "deny needs a reason: " + reasons},
		{"deny=", "deny needs a reason: " + reasons},
		{"deny=persn", `unknown reason "persn"; use ` + reasons},
		{"deny=person,generalise=host", `unknown reason "person,generalise=host"; use ` + reasons},
		{"generalise", `unknown term "generalise"; use ` + terms},
		{"generalise=domain,", "empty term"},
		{",pseudonymise", "empty term"},
		{"generalise=host,generalise=host", "generalise=host appears twice"},
		{"generalise=host,allow", "allow stands alone; it can't be combined with other terms"},
		{"pseudonymise,deny=person", "deny=person stands alone; it can't be combined with other terms"},
	}

	for _, test := range tests {
		t.Run(test.tag, func(t *testing.T) {
			_, err := umbra.ParseTag(test.tag, policy())
			if err == nil || err.Error() != test.want {
				t.Errorf("got %v, want %s", err, test.want)
			}
		})
	}
}

func TestParseTagWithoutBases(t *testing.T) {
	_, err := umbra.ParseTag("allow=business_data", umbra.Policy{Reasons: []umbra.Reason{"person"}})

	if want := `unknown basis "business_data"; the policy has none`; err == nil || err.Error() != want {
		t.Errorf("got %v, want %s", err, want)
	}
}

// FuzzGrammar checks that a tag parses back to the class it prints as, and that a class
// survives a catalog file: written, verified and loaded again.
func FuzzGrammar(f *testing.F) {
	pii := umbra.Policy{
		Reasons: []umbra.Reason{"person", "credential"},
		Bases:   []umbra.Basis{"business_data"},
		Maskers: []umbra.Masker{
			{Term: "generalise=domain", Suffix: "domain", Kinds: umbra.Text},
			{Term: "pseudonymise", Suffix: "pseudonym", Kinds: umbra.Text | umbra.UUID},
		},
	}

	for _, tag := range []string{
		"allow", "allow=business_data", "deny=person", "pseudonymise", "generalise=domain,pseudonymise",
		"", "deny", "deny=", "allow=", ",", "pseudonymise,", "allow,deny=person", "pseudonymise,pseudonymise",
	} {
		f.Add("email", tag)
	}

	f.Add("", "allow")
	f.Add("#email", "allow")
	f.Add("e mail", "allow")

	f.Fuzz(func(t *testing.T, column, tag string) {
		class, err := umbra.ParseTag(tag, pii)
		if err != nil {
			return
		}

		if class.String() != tag {
			t.Fatalf("ParseTag(%q) prints as %q", tag, class)
		}

		again, err := umbra.ParseTag(class.String(), pii)
		if err != nil || !reflect.DeepEqual(again, class) {
			t.Fatalf("%q parses as %#v, then as %#v (%v)", tag, class, again, err)
		}

		registry := umbra.NewRegistry(pii, nil)
		registry.Dataset("dataset").Columns("table", umbra.Tag(column, tag))

		catalog, err := registry.Catalog()
		if err != nil {
			return // a column name no catalog file can hold
		}

		files := fstest.MapFS{
			"dataset/table.pii": {Data: []byte("# Code generated by umbra. DO NOT EDIT.\n" + column + " " + tag + "\n")},
		}

		if err := catalog.Verify(files); err != nil {
			t.Fatalf("column %q, tag %q: %v", column, tag, err)
		}

		loaded, err := umbra.Load(files, pii)
		if err != nil {
			t.Fatalf("column %q, tag %q: %v", column, tag, err)
		}

		if !reflect.DeepEqual(loaded, catalog) {
			t.Fatalf("column %q, tag %q: loads as %#v, not %#v", column, tag, loaded, catalog)
		}
	})
}
